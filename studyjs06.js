// Group 2 : Loop/:Repeat/Internation Statements
// 1.while loop
let x = 1;
while (x <= 100) {
    console.log(`${x}. DIT-SAU`);
    x = x + 1
}
console.log('------------------------------');

// 2. do-while loop
let y = 1;
do {
    console.log(`${y}. DIT-SAU`);
    y = y + 1
} while (y <= 100);
console.log('------------------------------');

// 3. for loop
for (let z = 1; z <= 100; z = z + 1) {
    console.log(`${z}. DIT-SAU`);
}